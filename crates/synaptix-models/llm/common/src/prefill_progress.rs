//! Счётчик токенов префилла всех языковых моделей процесса — для графика
//! службы: префилл идёт кусками внутри генерации, а снаружи видно только его
//! начало и первый токен. Архитектуры добавляют пройденный кусок; служба
//! берёт приращение за интервал выборки как скорость префилла.

use std::sync::atomic::{AtomicU64, Ordering};

static TOKENS: AtomicU64 = AtomicU64::new(0);

/// Пройдено ещё `n` токенов префилла.
pub fn add(n: usize) {
    TOKENS.fetch_add(n as u64, Ordering::Relaxed);
}

/// Всего токенов префилла с запуска процесса.
pub fn total() -> u64 {
    TOKENS.load(Ordering::Relaxed)
}
